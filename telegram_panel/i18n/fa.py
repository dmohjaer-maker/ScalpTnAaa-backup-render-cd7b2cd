def translate(text: str | None) -> str:
    """Translate user-visible English UI text while preserving HTML and values."""
    if not text:
        return text or ""
    result = str(text)
    for source, target in _PHRASES:
        result = re.sub(re.escape(source), target, result, flags=re.IGNORECASE)
    for source, target in _WORDS:
        result = re.sub(rf"(?<![A-Za-z]){re.escape(source)}(?![A-Za-z])", target, result, flags=re.IGNORECASE)
    return result